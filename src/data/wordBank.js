export function findWordEntry(rawWord) {
  if (!rawWord) return null;
  const clean = rawWord.trim().toLowerCase();
  return WORD_BANK.find((entry) => entry.word.toLowerCase() === clean) || null;
}

export function pickRandomWordEntry(usedWords = [], levelFilter = 'Tutti') {
  const usedSet = new Set(usedWords.map((w) => w.trim().toLowerCase()));
  const poolByLevel =
    levelFilter === 'Tutti'
      ? WORD_BANK
      : WORD_BANK.filter((entry) => entry.level === levelFilter);

  const unused = poolByLevel.filter((entry) => !usedSet.has(entry.word.toLowerCase()));
  const candidates = unused.length > 0 ? unused : poolByLevel;
  const idx = Math.floor(Math.random() * candidates.length);
  return candidates[idx];
}

export function pickNonSynonymDistractors(entry, count = 4) {
  const pool = [...entry.distractors];
  for (let i = pool.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1));
    [pool[i], pool[j]] = [pool[j], pool[i]];
  }
  return pool.slice(0, count);
}

export function suggestDistractorsForCustomWord(targetWord, existingDistractors = []) {
  const forbidden = new Set(
    [targetWord, ...existingDistractors]
      .filter(Boolean)
      .map((w) => w.trim().toLowerCase())
  );

  const matched = findWordEntry(targetWord);
  if (matched) {
    const fromMatched = matched.distractors.filter((d) => !forbidden.has(d.toLowerCase()));
    if (fromMatched.length >= 4) {
      return fromMatched.slice(0, 4);
    }
  }

  const fallbackPool = WORD_BANK.map((e) => e.word).filter(
    (w) => !forbidden.has(w.toLowerCase())
  );
  for (let i = fallbackPool.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1));
    [fallbackPool[i], fallbackPool[j]] = [fallbackPool[j], fallbackPool[i]];
  }
  return fallbackPool.slice(0, 4);
}
